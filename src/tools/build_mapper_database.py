#!/usr/bin/env python3
"""Generate an offline ROM mapper database: sorted SHA-1 prefixes + uint8 type.

Example: python3 tools/build_mapper_database.py --output generated
To update upstream, replace tools/mapperdb/softwaredb.xml with a reviewed XML.
Add local images to tools/mapperdb/custom_roms.txt as FULL_SHA1 MAPPER.
"""
import argparse
import hashlib
import os
from pathlib import Path
import re
import struct
import tempfile
import xml.etree.ElementTree as ET
import zlib

HERE = Path(__file__).resolve().parent
ALIASES = {
    'KonamiUltimateCollection': 'KUC',
    'konami': 'Konami',
    'playball': 'Playball',
    'keyboardmaster': 'KeyboardMaster',
    'dooly': 'Dooly',
    'manbow2': 'Manbow2',
}


def canonical(name):
    if len(name) > 31 or not re.fullmatch(r'[A-Za-z0-9_-]+', name):
        raise ValueError(f'invalid mapper name: {name!r}')
    return ALIASES.get(name, name)


def convert(xml, custom=''):
    """Merge full identities before checking the shorter on-disk keys."""
    images = {}
    skipped = 0

    def add(digest, name):
        if not re.fullmatch(r'[0-9a-fA-F]{40}', digest):
            raise ValueError(f'invalid SHA-1: {digest!r}')
        digest = digest.lower()
        name = canonical(name)
        if digest in images and images[digest] != name:
            raise ValueError(f'conflicting mapper for SHA-1 {digest}')
        images[digest] = name

    for rom in ET.fromstring(xml).iter('rom'):
        if not rom.get('type'):
            skipped += 1
            continue
        add(rom.get('sha1', ''), rom.get('type'))
    upstream = dict(images)
    local = {}
    for number, line in enumerate(custom.splitlines(), 1):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = line.split()
        override = len(fields) == 3 and fields[2] == 'override'
        if len(fields) != 2 and not override:
            raise ValueError(f'custom line {number}: expected SHA1 MAPPER [override]')
        digest, name = fields[:2]
        digest = digest.lower()
        name = canonical(name)
        if not re.fullmatch(r'[0-9a-f]{40}', digest):
            raise ValueError(f'invalid SHA-1: {digest!r}')
        if digest in local and local[digest] != name:
            raise ValueError(f'conflicting custom mapper for SHA-1 {digest}')
        local[digest] = name
        if override:
            if digest not in upstream:
                raise ValueError(f'custom line {number}: override requires an upstream hash')
            images[digest] = name
        else:
            add(digest, name)

    # ID 0 is reserved; IDs are local to this file, not firmware enum values.
    names = [''] + sorted(set(images.values()) | {'Plain', 'SCCI', 'SCCPlus'})
    if len(names) > 256:
        raise ValueError('mapper IDs no longer fit one byte')
    ids = {name: i for i, name in enumerate(names)}
    prefixes = {}
    rows = []
    for digest, name in sorted(images.items()):
        prefix = bytes.fromhex(digest)[:7]
        if prefix in prefixes and prefixes[prefix] != digest:
            raise ValueError(f'SHA-1 prefix collision: {prefixes[prefix]} / {digest}')
        prefixes[prefix] = digest
        rows.append(prefix + bytes([ids[name]]))
    return b''.join(rows), names, skipped


def write_changed(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    # Different board builds may regenerate the same deterministic artifacts.
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as output:
        output.write(data)
        temporary = output.name
    os.replace(temporary, path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--xml', type=Path, default=HERE / 'mapperdb/softwaredb.xml')
    parser.add_argument('--custom', type=Path, default=HERE / 'mapperdb/custom_roms.txt')
    parser.add_argument('--output', type=Path, default=HERE.parent / 'generated')
    args = parser.parse_args()
    try:
        xml = args.xml.read_bytes()
        custom = args.custom.read_text() if args.custom.exists() else ''
        data, names, skipped = convert(xml, custom)
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, f'{error}\n')

    # Only names are compiled: hash records stay in the external binary.
    header = [
        '// Generated by tools/build_mapper_database.py; do not edit.',
        '#pragma once',
        '#include <cstdint>',
        f'inline constexpr unsigned MapperDatabaseCount = {len(data) // 8};',
        'inline constexpr const char* MapperDatabaseNames[] = {',
    ]
    header += [f'    "{name}",' for name in names]
    header += ['};', '']
    # Names are shared with Z80 display filtering, including the long KUC alias.
    tags = sorted(set(names[1:]) | {'KonamiUltimateCollection', 'SCC+'})
    assembly = ['; Generated recognized mapper tags.', 'MapperTagNames:']
    assembly += [f'    db "{name}", 0' for name in tags]
    assembly += ['    db 0', '']

    dictionary = b''.join(name.encode().ljust(32, b'\0') for name in names)
    offset = 40 + len(dictionary)
    body = dictionary + data
    header_bytes = b'OSROMDB1' + struct.pack(
        '<7I', 1, 8, len(data) // 8, len(names), offset,
        40 + len(body), zlib.crc32(body),
    )
    header_bytes += struct.pack('<I', zlib.crc32(header_bytes))
    write_changed(args.output / 'romdb.bin', header_bytes + body)
    write_changed(args.output / 'mapper_database.hxx', '\n'.join(header).encode())
    write_changed(args.output / 'mapper_tags.inc', '\n'.join(assembly).encode())
    print(
        f'{len(data) // 8} ROMs, {len(names) - 1} mapper names, '
        f'{len(header_bytes) + len(body)} file bytes ({len(data)} record bytes); '
        f'{skipped} rows without type skipped'
    )
    print(f'XML SHA256 {hashlib.sha256(xml).hexdigest()}')


if __name__ == '__main__':
    main()
