#!/usr/bin/env python3
"""Generate the browser font, Screen 5 menu titles and shared startup logo.

Run after editing the artwork. All generated assets are checked in, so the
firmware build needs only sjasmplus. The favourites menu keeps the full font.
"""
from pathlib import Path
import re
import struct
import zlib

HERE = Path(__file__).resolve().parent
WIDTH, HEIGHT = 192, 20
# Screen 5 palette indices: background, white, cyan, yellow.
RGB = {4: (84, 85, 237), 15: (255, 255, 255),
       7: (66, 235, 245), 10: (212, 193, 84)}
LETTERS = {
    'O': ('01110', '10001', '10001', '10001', '10001', '10001', '01110'),
    'm': ('00000', '00000', '11010', '10101', '10101', '10101', '10101'),
    'n': ('00000', '00000', '11110', '10001', '10001', '10001', '10001'),
    'i': ('00100', '00000', '01100', '00100', '00100', '00100', '01110'),
    'S': ('01111', '10000', '10000', '01110', '00001', '00001', '11110'),
    'C': ('01111', '10000', '10000', '10000', '10000', '10000', '01111'),
    'e': ('00000', '00000', '01110', '10001', '11111', '10000', '01111'),
    'x': ('00000', '00000', '10001', '01010', '00100', '01010', '10001'),
    'p': ('00000', '00000', '11110', '10001', '11110', '10000', '10000'),
    'l': ('01100', '00100', '00100', '00100', '00100', '00100', '01110'),
    'o': ('00000', '00000', '01110', '10001', '10001', '10001', '01110'),
    'r': ('00000', '00000', '10110', '11001', '10000', '10000', '10000'),
    'a': ('00000', '00000', '01110', '00001', '01111', '10001', '01111'),
    'u': ('00000', '00000', '10001', '10001', '10001', '10001', '01111'),
    'c': ('00000', '00000', '01111', '10000', '10000', '10000', '01111'),
    'h': ('10000', '10000', '11110', '10001', '10001', '10001', '10001'),
}


def asm_bytes(data):
    return ''.join('    db ' + ', '.join(f'${v:02X}' for v in data[i:i+16]) + '\n'
                   for i in range(0, len(data), 16))


def make_title(subtitle='explorer'):
    pixels = [[4] * WIDTH for _ in range(HEIGHT)]
    # Three slanted signal bars lead into the wordmark.
    for y in range(4, 16):
        for bar in range(3):
            for dx in range(2):
                pixels[y][bar*5 + (15-y)//3 + dx] = 15 if y < 8 else 7
    def text(word, x0, y0, scale, italic=False):
        for index, char in enumerate(word):
            for row, bits in enumerate(LETTERS[char]):
                slant = (6-row)//2 if italic else 0
                color = (15 if row < 3 else 7) if italic else 10
                for col, bit in enumerate(bits):
                    if bit == '1':
                        for dy in range(scale):
                            for dx in range(scale):
                                pixels[y0 + row*scale + dy][x0 + index*6*scale + col*scale + dx + slant] = color
    text('OmniSCC', 22, 2, 2, italic=True)
    text(subtitle, 122, 7, 1)
    # A thin speed line balances the small explorer lettering.
    for x in range(22, 101):
        pixels[18][x] = 7
    for x in (104, 105, 109, 110):
        pixels[18][x] = 15
    return pixels


PALETTE = (4, 15, 7, 10)


def rle_rows(pixels):
    # One byte: run length minus one (high nibble), two 2-bit colors (low).
    # Rows end after half the image width in output bytes.
    encoded = []
    for row in pixels:
        packed = [PALETTE.index(row[x])*4 + PALETTE.index(row[x+1])
                  for x in range(0, len(row), 2)]
        start = 0
        while start < len(packed):
            end = start + 1
            while end < min(len(packed), start+16) and packed[end] == packed[start]:
                end += 1
            encoded.append(((end-start-1) << 4) | packed[start])
            start = end
    return encoded


def save_png(pixels, name):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))
    raw = b''.join(b'\0' + bytes(v for color in row for v in RGB[color]) for row in pixels)
    png = b'\x89PNG\r\n\x1a\n'
    png += chunk(b'IHDR', struct.pack('>IIBBBBB', len(pixels[0]), len(pixels), 8, 2, 0, 0, 0))
    png += chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b'')
    (HERE / name).write_bytes(png)


def main():
    # PrintableChar restricts browser text to ASCII; high glyphs are unused.
    font = [int(v, 16) for v in re.findall(r'#([0-9a-fA-F]{2})', (HERE/'font.inc').read_text())]
    assert len(font) == 2048
    (HERE/'loader_font.inc').write_text(
        '; Generated by build_loader_art.py from font.inc (ASCII 32..127).\n'
        '; Carnivore2+ font, Copyright (c) 2024 RBSC, Version 3.00.\n' + asm_bytes(font[32*8:128*8]))
    for name, subtitle in (('loader', 'explorer'), ('loader_fav', 'launcher')):
        pixels = make_title(subtitle)
        data = rle_rows(pixels)
        (HERE/f'{name}_title.inc').write_text(
            '; Generated by build_loader_art.py: run-1 in high nibble, 2-bit palette pair in low.\n'
            f'TITLE_WIDTH    EQU {WIDTH}\nTITLE_HEIGHT   EQU {HEIGHT}\n'
            'TitleBitmap:\n' + asm_bytes(data) + 'TitleBitmapEnd:\n')
        save_png(pixels, f'{name}_title.png')
        print(f'{subtitle}: {WIDTH}x{HEIGHT} title, {len(data)} RLE bytes')
    # Reuse the wordmark unchanged, cropped before the menu-specific subtitle.
    logo = [row[:112] for row in make_title('')]
    data = rle_rows(logo)
    (HERE/'startup_logo.inc').write_text(
        '; Generated by build_loader_art.py: shared startup wordmark without subtitle.\n'
        'STARTUP_LOGO_WIDTH EQU 112\nSTARTUP_LOGO_HEIGHT EQU 20\n'
        'StartupLogoBitmap:\n' + asm_bytes(data) + 'StartupLogoBitmapEnd:\n')
    save_png(logo, 'startup_logo.png')
    print(f'startup: 112x20 wordmark, {len(data)} RLE bytes')


if __name__ == '__main__':
    main()
