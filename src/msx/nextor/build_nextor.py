#!/usr/bin/env python3
"""Package the pinned Nextor base with the dedicated OmniSCC driver."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess

UPSTREAM_HASH='f3e77baa45ca3938f13cc70b57e0a075373ab9f0'
BASE_SHA256='d574417d6c607406b4ed6c01ccfc742b1e739dfe7e5e484ffb509eb90add3ab8'
DRIVER_NAME=b'OmniSCC shared flash'
PACKAGER_SHA256='afc3e65ae79c86b036303c9b9141f704f0daf0bb4a0b459d744c087fccb43b54'
SOURCE=Path(__file__).resolve().parent
PROJECT=SOURCE.parents[2]
HOST_EXE_SUFFIX='.exe' if os.name=='nt' else ''

def host_compiler():
    override=os.environ.get('CC')
    candidates=(override,) if override else ('cc','gcc','clang')
    for candidate in candidates:
        compiler=shutil.which(candidate)
        if compiler:
            return compiler
    raise ValueError('Host C compiler not found; install GCC or Clang and '
                     'add it to PATH, or set CC to the compiler executable path '
                     '(not the ARM cross-compiler)')

def validate_rom(rom):
    if not rom or len(rom)%16384 or len(rom)>131072 or len(rom)<32768:
        raise ValueError('invalid Nextor ROM size')
    banks=len(rom)//16384
    driver=rom[0xFE]
    if not 0<driver<banks or driver+1!=banks or rom[:2]!=b'AB':
        raise ValueError('invalid Nextor kernel/driver bank count')
    p=driver*16384
    if rom[p+0x100:p+0x10E]!=b'NEXTOR_DRIVER\0' or rom[p+0x10E]!=1 or rom[p+0x110:p+0x110+len(DRIVER_NAME)]!=DRIVER_NAME:
        raise ValueError('not an OmniSCC Nextor driver')
    for i in range(banks):
        q=i*16384
        if rom[q:q+2]!=b'AB' or rom[q+0xFE]!=driver or rom[q+0xFF]!=i or rom[q+0x3FD0:q+0x3FD4]!=bytes.fromhex('32ff7fc9'):
            raise ValueError('invalid bank identity or mapper')
    return {'bank_count':banks,'driver_bank':driver}

def assemble_driver(output):
    output=Path(output).resolve();output.mkdir(parents=True,exist_ok=True)
    source=Path(__file__).resolve().parent
    # SAVEBIN is relative to cwd; keep all generated bytes out of msx/.
    subprocess.run([os.environ.get('SJASMPLUS') or shutil.which('sjasmplus') or 'sjasmplus', '--inc='+source.as_posix(), '--sym='+(output/'driver.sym').as_posix(), (source/'nextor_driver.asm').as_posix()],cwd=output,check=True)
    data=(output/'nextor_driver.bin').read_bytes()
    if len(data)!=16384 or data[0x100:0x10E]!=b'NEXTOR_DRIVER\0':
        raise ValueError('invalid driver assembly')
    symbols={}
    for line in (output/'driver.sym').read_text().splitlines():
        if ': EQU 0x' in line:
            name,value=line.split(': EQU 0x');symbols[name]=int(value,16)
    if symbols['CodeEnd']>0x6000 or symbols['Exchange']!=0x6000 or symbols['Parameters']!=0x7F80 or symbols['BankTail']!=0x7FD0:
        raise ValueError('driver overlaps reserved mailbox or bank tail')
    return data

def build(upstream,output,base=None):
    upstream=Path(upstream).resolve();output=Path(output).resolve();output.mkdir(parents=True,exist_ok=True)
    if not (upstream/'.git').exists():
        raise ValueError('Nextor submodule is not initialized; run '
                         'git submodule update --init src/msx/nextor/upstream '
                         'from the repository root')
    revision=subprocess.check_output(['git','-C',str(upstream),'rev-parse','HEAD'],text=True).strip()
    if revision!=UPSTREAM_HASH: raise ValueError('upstream is not pinned Nextor v2.1.3')
    packager=upstream/'buildtools/sources/mknexrom.c'
    # Git's Windows autocrlf changes only line endings; verify canonical LF.
    source_bytes=packager.read_bytes().replace(b'\r\n',b'\n')
    if hashlib.sha256(source_bytes).hexdigest()!=PACKAGER_SHA256:
        raise ValueError('pinned MKNEXROM source checksum mismatch')
    if base is None:
        base=PROJECT/'tools/nextor-base.dat'
    base=Path(base).resolve()
    raw=base.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=BASE_SHA256: raise ValueError('base ROM checksum mismatch; obtain official Nextor-2.1.3.base.dat')
    compiler=host_compiler()
    driver=assemble_driver(output)
    mapper=output/'mapper.bin';mapper.write_bytes(driver[0x3FD0:0x4000])
    (output/'driver_payload.bin').write_bytes(driver[:0x3FD0])
    tool=output/('mknexrom'+HOST_EXE_SUFFIX)
    subprocess.run([compiler,'-O2','-Wno-unused-result',packager.as_posix(),'-o',tool.as_posix()],check=True)
    rom=output/'nextor.rom'
    subprocess.run([str(tool),base.as_posix(),'nextor.rom','/d:driver_payload.bin','/m:mapper.bin'],cwd=output,check=True)
    # Pinned 2.1.3 BSEC_TYPE compares "FAT1" to identify standard BPBs.
    # Production FatFs emits "FAT     " for both FAT12 and FAT16. Compare
    # the three-byte prefix so these valid volumes do not force DOS1 mode.
    # Keep the filesystem unchanged; refuse any unexpected kernel layout.
    data=bytearray(rom.read_bytes())
    expected=bytes.fromhex('2136c01136560604cd405620033e02c9afc946415431')
    if data[0x1624:0x1624+len(expected)] != expected:
        raise ValueError('unexpected pinned BSEC_TYPE layout')
    data[0x162B]=3
    rom.write_bytes(data)
    info=validate_rom(rom.read_bytes())
    info.update(upstream_revision=revision,base_sha256=BASE_SHA256,rom_sha256=hashlib.sha256(rom.read_bytes()).hexdigest(),exchange_start=0x6000,exchange_end=0x7600,assembler=Path(os.environ.get('SJASMPLUS') or shutil.which('sjasmplus')).name,packager='MKNEXROM 1.06')
    info['kernel_patches']=['BSEC_TYPE FAT prefix length 4 -> 3 at bank 0 offset 0x162B']
    (output/'manifest.json').write_text(json.dumps(info,indent=2)+'\n')
    shutil.copyfile(upstream/'LICENSE.md',output/'NEXTOR-LICENSE.md')
    print('OK Nextor ROM:',rom)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream',type=Path,default=SOURCE/'upstream',help='initialized pinned Nextor submodule or original Git checkout')
    parser.add_argument('--output',type=Path,default=PROJECT/'src/generated/nextor')
    parser.add_argument('--base',type=Path,help='official Nextor base ROM; defaults to tools/nextor-base.dat')
    args=parser.parse_args()
    try:
        build(args.upstream,args.output,args.base)
    except (ValueError,FileNotFoundError,subprocess.CalledProcessError) as error:
        parser.exit(1,f'ERROR: {error}\n')
