#!/usr/bin/env python3
"""Resize the official RBSC emblem and encode native SCREEN 5 pair runs.

Source: https://rbsc.su/images_s/rbsc_logo.jpg (RBSC).
Requires Pillow only when regenerating; the ROM build uses checked-in data.
Each byte stores (run length - 1) in its high nibble and a palette-pair index
in its low nibble. Runs never cross a scanline, and contain at most 16 pairs.
"""
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
WIDTH, HEIGHT = 128, 134
# Classify against the original artwork, then use existing menu palette entries:
# blue background, white outline, yellow bear. No palette changes at runtime.
SOURCE_COLORS = ((57,61,112), (255,255,255), (249,237,45))
MENU_COLORS = ((84,85,237), (255,255,255), (212,193,84))
image = Image.open(HERE/'rbsc_logo_source.jpg').convert('RGB')
image = image.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
pixels = [min(range(3), key=lambda i: sum((p[c]-SOURCE_COLORS[i][c])**2
                                        for c in range(3)))
          for p in image.get_flattened_data()]
encoded = []
for y in range(HEIGHT):
    pairs = [pixels[y*WIDTH+x]*3+pixels[y*WIDTH+x+1]
             for x in range(0,WIDTH,2)]
    start = 0
    while start < len(pairs):
        count = 1
        while count < 16 and start+count < len(pairs) and pairs[start+count] == pairs[start]:
            count += 1
        encoded.append((count-1)*16+pairs[start])
        start += count
image.putdata([MENU_COLORS[p] for p in pixels])
image.save(HERE/'rbsc_logo.png')
lines = ['; Generated by build_rbsc_art.py; official emblem from https://rbsc.su/en/.',
         f'RBSC_WIDTH EQU {WIDTH}', f'RBSC_HEIGHT EQU {HEIGHT}', 'RbscBitmap:']
for start in range(0,len(encoded),16):
    lines.append('    db '+', '.join(f'${v:02X}' for v in encoded[start:start+16]))
(HERE/'rbsc_logo.inc').write_text('\n'.join(lines)+'\n')
print(f'RBSC emblem: {WIDTH}x{HEIGHT}, {len(encoded)} RLE bytes')
